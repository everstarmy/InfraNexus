import { expect, test } from "@playwright/test"
test("gallery exposes presets, row actions, refreshing and recoverable errors without console errors", async ({
  page,
}, info) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  page.on("console", message => { if (message.type() === "error" || message.type() === "warning") errors.push(message.text()) })
  await page.goto("/__e2e__/data-table?gallery=1")
  await expect(page.getByRole("navigation", { name: "表格场景" })).toBeVisible()
  await page.getByRole("button", { name: "presets", exact: true }).click()
  await page.getByLabel("能力预设").selectOption("simple")
  await expect(page.getByRole("button", { name: "表格密度" })).toHaveCount(0)
  const downloadPromise = page.waitForEvent("download")
  await page.getByRole("button", { name: "导出当前页", exact: true }).click()
  expect((await downloadPromise).suggestedFilename()).toBe("gallery.csv")
  await page.getByLabel("能力预设").selectOption("advanced")
  await expect(page.getByRole("button", { name: "表格密度" })).toBeVisible()
  await page.getByRole("button", { name: "更多行操作" }).click()
  await page.getByRole("menuitem", { name: "查看", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("已查看")
  await page.getByRole("button", { name: "模拟刷新", exact: true }).click()
  await expect(page.getByRole("progressbar", { name: "正在更新表格数据" })).toBeVisible()
  await page.getByRole("button", { name: "模拟错误", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("数据加载失败")
  await expect(page.getByText("示例成员", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "切换空数据" }).click()
  await expect(page.getByRole("alert")).toBeVisible()
  await page.getByRole("button", { name: "重试", exact: true }).click()
  await expect(page.getByRole("alert")).toHaveCount(0)
  await page.getByRole("button", { name: "virtualized", exact: true }).click()
  await expect(page.locator("table[data-virtualized=true]")).toBeVisible()
  await expect(page.locator("tbody tr[data-row-id]")).not.toHaveCount(10000)
  await page.screenshot({ path: info.outputPath("enterprise-gallery.png") })
  expect(errors).toEqual([])
})

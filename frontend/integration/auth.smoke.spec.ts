import { expect, test } from '@playwright/test'

test('real proxy, Cookie session, authorization and logout', async ({ page, context }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const ready = await context.request.get('/api/v1/ready')
  expect(ready.status()).toBe(200)
  await page.goto('/login')
  await page.getByLabel('用户名', { exact: true }).fill('admin')
  await page.getByLabel('登录密码', { exact: true }).fill('Smoke!Admin2468')
  await page.getByRole('button', { name: '登录控制台', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('authenticated-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('authenticated-mobile.png') })
  await page.setViewportSize({ width: 1280, height: 720 })
  const cookie = (await context.cookies()).find(cookie => cookie.name === 'infranexus_session')
  expect(cookie?.httpOnly).toBe(true)
  expect(cookie?.sameSite).toBe('Lax')
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  const profile = await context.request.get('/api/v1/auth/me')
  expect((await profile.json()).data.username).toBe('admin')
  const created = await context.request.post('/api/v1/users', { headers: { Origin: String(testInfo.project.use.baseURL) }, data: {
    username: 'smoke-no-roles', password: 'Smoke!User2468', nickname: 'Smoke user', email: 'smoke@example.test', status: 1, role_ids: [],
  } })
  expect(created.status()).toBe(200)
  await page.getByRole('button').filter({ hasText: '超级管理员' }).click()
  const logoutResponse = page.waitForResponse(response => response.url().endsWith('/auth/logout') && response.request().method() === 'POST')
  await page.getByRole('menuitem', { name: '退出登录' }).click()
  expect((await logoutResponse).status()).toBe(200)
  await expect(page).toHaveURL(/\/login/)
  expect((await context.request.get('/api/v1/auth/me')).status()).toBe(401)
  await page.goto('/users')
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('用户名', { exact: true }).fill('smoke-no-roles')
  await page.getByLabel('登录密码', { exact: true }).fill('Smoke!User2468')
  await page.getByRole('button', { name: '登录控制台', exact: true }).click()
  await expect(page.getByText('当前账号的角色未授予该页面的访问权限', { exact: false })).toBeVisible()
  expect((await context.request.get('/api/v1/users')).status()).toBe(403)
  expect(errors).toEqual([])
})
